BY_RULE = {"Таблетница": tabletnitsa, "Спортивный массажный мяч": myach}


def package_sizes(book):
    """«Размер упаковки … см» собираем из габаритов на листе «Товары».

    Там они в миллиметрах — Ozon в этом поле хочет сантиметры.
    """
    ws = book["Товары"]
    header = {ws.cell(row=1, column=c).value: c for c in range(1, ws.max_column + 1)}
    sizes = {}
    for r in range(3, ws.max_row + 1):
        article = ws.cell(row=r, column=header["Артикул *"]).value
        if not article:
            continue
        dims = [ws.cell(row=r, column=header[f"{name} упаковки, мм *"]).value
                for name in ("Длина", "Ширина", "Высота")]
        if all(isinstance(d, (int, float)) for d in dims):
            sizes[article] = " x ".join(
                f"{d / 10:g}".replace(".", ",") for d in dims)
    return sizes


def load_refs(book):
    ws = book["Справочники"]
    refs = {}
    for c in range(1, ws.max_column + 1):
        name = ws.cell(row=1, column=c).value
        refs[name] = {ws.cell(row=r, column=c).value
                      for r in range(2, ws.max_row + 1)
                      if ws.cell(row=r, column=c).value}
    return refs


def allowed(refs, category, column):
    plain = column.rstrip(" *")
    return refs.get(f"{category} — {plain}") or refs.get(f"Общий — {plain}")


def main(path):
    book = openpyxl.load_workbook(path)
    refs = load_refs(book)
    sizes = package_sizes(book)

    planned = defaultdict(dict)   # (лист, строка) → {колонка: значение}
    problems, empty = [], defaultdict(list)

    for category in COMMON:
        if category not in book.sheetnames:
            problems.append(f"нет листа «{category}»")
            continue
        ws = book[category]
        header = {ws.cell(row=1, column=c).value: c for c in range(1, ws.max_column + 1)}

        for r in range(3, ws.max_row + 1):
            article = ws.cell(row=r, column=1).value
            if not article:
                continue
            values = dict(COMMON[category])
            if category in BY_RULE:
                values.update(BY_RULE[category](article))
            values.update(PER_ARTICLE.get(article, {}))
            # Колонка есть не у всех категорий — ставим только там, где есть.
            pack = "Размер упаковки (Длина х Ширина х Высота), см"
            if article in sizes and pack in header:
                values.setdefault(pack, sizes[article])

            for column, value in values.items():
                if column not in header:
                    problems.append(f"{category}: нет колонки «{column}»")
                    continue
                options = allowed(refs, category, column)
                if options and str(value) not in {str(o) for o in options}:
                    problems.append(
                        f"{category} / {article}: «{value}» нет в списке «{column}»")
                    continue
                planned[(category, r)][header[column]] = value

            for column, c in header.items():
                if c == 1 or column in values:
                    continue
                if not ws.cell(row=r, column=c).value:
                    empty[category].append(column)

    if problems:
        print("НЕ СОВПАЛО СО СПРАВОЧНИКОМ — в книгу не записано ничего:")
        for p in sorted(set(problems)):
            print("  ", p)
        return 1

    written = 0
    for (category, r), cells in planned.items():
        ws = book[category]
        for c, value in cells.items():
            cell = ws.cell(row=r, column=c, value=value)
            cell.fill = GREEN
            written += 1
    book.save(path)

    print(f"записано значений: {written}")
    print("\nОсталось пустым (нет подтверждённого факта):")
    for category, columns in sorted(empty.items()):
        counted = {}
        for column in columns:
            counted[column] = counted.get(column, 0) + 1
        names = ", ".join(f"{k} ({v})" for k, v in sorted(counted.items()))
        print(f"  {category}: {names}")
    return 0


