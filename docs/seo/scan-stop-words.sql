with kw(kw, risk, rtype) as (values
  ('медицинск',      'A','Приглашает вопрос о группе «Медизделия»'),
  ('реабилитац',     'A','Довод за медицинское назначение'),
  ('чехол',          'A','Терминология позиции 4202'),
  ('зубная щетк',    'R','Позиция 9603 21 — маркировка с 01.10.2026'),
  ('омолажива',      'A','Заявление о результате без подтверждения'),
  ('лечебн',         'R','Лечебные свойства без РУ'),
  ('компрессион',    'R','Признак позиции 6212 (легпром, КИЗ)'),
  ('новорожден',     'R','ТР ТС 008/2011: требует ДС на игрушки')
)
select
  c.subject_name,
  c.my_article,
  c.wb_article,
  k.risk,
  k.rtype,
  k.kw,
  ch.value ->> 'name'                as field_name,
  ch.value -> 'value'                as field_value
from public.sku_catalog c
cross join lateral jsonb_array_elements(c.characteristics) as ch(value)
join kw k
  on lower(ch.value::text) like '%' || k.kw || '%'
order by
  case k.risk when 'R' then 1 else 2 end,
  c.subject_name, c.my_article, k.kw;
