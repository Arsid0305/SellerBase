-- Снять уникальность с колонки srid в wb_reports_fact.
--
-- Откуда взялось. В 0001_initial_schema.sql колонка объявлена как
-- «srid text not null unique» — тогда считалось, что srid и есть ключ строки.
-- В 0012_use_rrd_id_as_row_key.sql это исправили: ключом стал rrd_id, потому
-- что WB присылает несколько строк на один srid (продажа, логистика,
-- хранение, штрафы). Но 0012 снял первичный ключ и обычный индекс, а вот
-- ограничение wb_reports_fact_srid_key, созданное словом unique в 0001,
-- осталось в файлах.
--
-- Почему это важно. В рабочей базе ограничения нет — его когда-то сняли
-- руками, поэтому отчёты грузятся правильно: 187 296 строк, 40 281 srid
-- встречается больше одного раза, дублей по rrd_id нет. А вот база,
-- собранная из файлов репозитория, получала это ограничение и принять
-- реальные отчёты уже не могла. Расхождение нашла ежедневная сверка схемы.
--
-- Здесь правка холостая для рабочей базы (ограничения там нет) и лечит
-- сборку из файлов.

alter table public.wb_reports_fact
  drop constraint if exists wb_reports_fact_srid_key;

comment on column public.wb_reports_fact.srid is
  'ID заказа WB. Может повторяться: одна продажа — много операций. Ключ строки — rrd_id.';
