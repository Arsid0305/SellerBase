-- Словарь правил проверки карточек. Машинная версия docs/seo/stop-words.md.
-- Нужен в базе, потому что проверка строится как view (принцип №4), а view
-- не может читать markdown.
--
-- risk:
--   R — признак реально меняет классификацию или требует другого допуска
--   A — код не меняется, но слово даёт довод против классификации и путает алгоритмы
--   G — рабочий ключ: его ОТСУТСТВИЕ в группе есть дефект
--
-- except_subjects — предметы WB, где правило R/A не применяется. Ключевое поле:
--   одно и то же слово в разных группах значит разное. «игрушка» размывает предмет
--   в спорттоварах и является предметом в товарах для животных; «массажёр» — риск
--   для тех, кого выводят из 9019, и целевой ключ там, где 9019 нужен.
--
-- only_subjects — для G: где ключ обязателен.
--
-- strip_patterns — что вырезать из текста ДО поиска слова. Гасит известные ложные
--   срабатывания в источнике.

CREATE TABLE IF NOT EXISTS public.seo_stop_words (
  id              BIGSERIAL PRIMARY KEY,
  kw              TEXT NOT NULL,
  risk            TEXT NOT NULL CHECK (risk IN ('R','A','G')),
  note            TEXT,
  replacement     TEXT,
  except_subjects TEXT[] NOT NULL DEFAULT '{}',
  only_subjects   TEXT[] NOT NULL DEFAULT '{}',
  strip_patterns  TEXT[] NOT NULL DEFAULT '{}',
  active          BOOLEAN NOT NULL DEFAULT true,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS seo_stop_words_kw_risk_idx
  ON public.seo_stop_words (kw, risk);

ALTER TABLE public.seo_stop_words ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS seo_stop_words_select_auth ON public.seo_stop_words;
CREATE POLICY seo_stop_words_select_auth ON public.seo_stop_words
  FOR SELECT TO authenticated USING (true);

COMMENT ON TABLE public.seo_stop_words IS
  'Правила проверки карточек. Источник: docs/seo/stop-words.md. Новые слова — новой миграцией.';

