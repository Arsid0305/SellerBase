-- Калибровка словаря по факту первого прогона v_sku_seo_issues.
--
-- 1) «новорожден» ловилось в 7 мешках для стирки на формулировке
--    «для детской одежды и вещей новорождённого малыша». Это описание того,
--    ЧТО стирают, а не для кого товар — 🟢 в docs/seo/stop-words.md.
--    Само правило нужное: «для новорождённых» как назначение требует ДС по ТР ТС 008/2011.
--
-- 2) У «детск» паттерн был «для детской одежды», но в половине текстов идёт
--    «хранения детской одежды» — без предлога. Ослабляем до «детской одежды».

UPDATE public.seo_stop_words
   SET strip_patterns = ARRAY[
         'вещей новорожденного',
         'вещи новорожденного',
         'вещей новорожденного малыша'
       ]
 WHERE kw = 'новорожден' AND risk = 'R';

UPDATE public.seo_stop_words
   SET strip_patterns = ARRAY[
         'в недоступном для детей месте',
         'детской одежды',
         'детских вещей',
         'детским мылом',
         'вещей новорожденного'
       ]
 WHERE kw = 'детск' AND risk = 'A';

UPDATE public.seo_stop_words
   SET strip_patterns = ARRAY['в недоступном для детей месте']
 WHERE kw = 'для детей' AND risk = 'A';
