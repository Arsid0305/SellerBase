-- Живой склад теперь один - «Склад WB РФ». Остальные строки отчёта ВБ
-- держат остаток, которого фактически нет.
--
-- Решение владелицы 17.09.2026: «живой только Склад WB РФ, именно так
-- теперь будет называться склад, он будет один».
--
-- Что показали данные. 16.08.2026 ВБ схлопнул шесть складов в строку
-- «Склад WB РФ», и 1 487 штук уехали в «в пути возвраты на склад WB»
-- (было 23, стало 1 510) - висят там месяц. За месяц после этого
-- двигался только «Склад WB РФ» (-140 штук), а Электросталь 2 120,
-- Краснодар 435 и Тула 390 не изменились ни на штуку. Контрольная
-- проверка: 111 продаж из 113 за месяц уехали со «Склада WB РФ».
--
-- Из-за мёртвого остатка врали «дней запаса», «залежалось» и дефицит:
-- программа считала, что запаса хватит на годы, и молчала.
--
-- Механизм уже есть: строки из wb_stock_service_rows загрузчик пишет
-- только в историю и не кладёт в wb_stocks. Добавляем туда мёртвые
-- склады. История остаётся полной - это первоисточник.

-- Раньше строка могла быть только итогом, свёрткой или товаром в пути.
-- Добавляем вид «frozen» - настоящий склад, но остаток на нём мёртвый.
