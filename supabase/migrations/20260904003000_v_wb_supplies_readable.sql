-- Читаемое представление поставок: статусы словами и даты по Москве.
--
-- Владелица прислала скриншот кабинета 04.09 — сверка пяти поставок дала две вещи.
--
-- 1. Словарь статусов, выверенный по полному списку кабинета (73 строки):
--      statusID = 5 → «Принято»          — 70 поставок, все с этой подписью;
--      statusID = 1 → «Не запланировано» — три преордера (53384170, 53361762,
--                                          50569801), даты создания совпали.
--    Типы поставки: boxTypeID = 2 → «Короб», boxTypeID = 0 → «Допринято».
--    Прочие коды не выдумываем: увидим в кабинете — впишем.
--
--    «Истёк срок поставки» статусом не является: в кабинете это подпись вместо
--    даты у допринятых поставок, у которых нет фактической даты. Здесь она
--    видна тем, что «Дата фактическая» пуста.
--
-- 2. Даты уезжали на день назад. WB отдаёт «2026-06-13T00:00:00+03:00»;
--    в UTC это 12 июня 21:00, и приведение к дате давало 12-е вместо 13-го.
--    Поставка 39772509 в кабинете «6 июня → 7 июня», в базе выходила 5-е и 6-е.
--    Хранение остаётся timestamptz (так верно), а показываем в Москве.
--
-- Соответствие столбцам кабинета:
--   «Добавлено, шт» → quantity;  «Принято» → accepted_quantity.
--   «Упаковано» API не отдаёт вовсе — в кабинете оно есть, у нас его нет.
--
-- Колонки «расхождение» здесь намеренно НЕТ. В кабинете пометка «1 ошибка»
-- считается от упакованного (1117 добавлено → 1133 упаковано → 1132 принято:
-- потеря одной единицы). Без «упаковано» разность «добавлено минус принято»
-- показывает не потерю, а доложенное в короб: у поставки 39772509 вышло бы
-- −15, будто приняли больше, чем отправили. Такую колонку лучше не иметь,
-- чем иметь неверную.

CREATE OR REPLACE VIEW public.v_wb_supplies
WITH (security_invoker = true) AS
SELECT
  s.id,
  s.supply_id_num                                             AS "Номер поставки",
  nullif(s.preorder_id, 0)                                    AS "Номер преордера",
  CASE s.status_id
    WHEN 1 THEN 'Не запланировано'
    WHEN 5 THEN 'Принято'
    ELSE 'Статус ' || coalesce(s.status_id::text, '—')
  END                                                          AS "Статус",
  CASE s.box_type_id
    WHEN 0 THEN 'Допринято'
    WHEN 2 THEN 'Короб'
    ELSE 'Тип ' || coalesce(s.box_type_id::text, '—')
  END                                                          AS "Тип поставки",
  (s.supply_date AT TIME ZONE 'Europe/Moscow')::date           AS "Дата плановая",
  (s.fact_date   AT TIME ZONE 'Europe/Moscow')::date           AS "Дата фактическая",
  (s.date_created AT TIME ZONE 'Europe/Moscow')::date          AS "Создана",
  s.warehouse_name                                             AS "Склад",
  nullif(s.actual_warehouse_name, '')                          AS "Склад фактический",
  nullif(s.transit_warehouse_name, '')                         AS "Склад транзитный",
  s.quantity                                                   AS "Добавлено, шт",
  s.accepted_quantity                                          AS "Принято, шт",
  s.ready_for_sale_quantity                                    AS "Готово к продаже, шт",
  s.acceptance_cost                                            AS "Платная приёмка, ₽",
  s.paid_acceptance_coef                                       AS "Коэффициент приёмки",
  s.reject_reason                                              AS "Причина отказа",
  (s.updated_date AT TIME ZONE 'Europe/Moscow')                AS "Обновлено WB"
FROM public.wb_supplies_v2 s;

COMMENT ON VIEW public.v_wb_supplies IS
  'Поставки FBW как в кабинете: статусы словами, даты по Москве. Словарь выверен по полному списку кабинета 04.09.2026 — статус 5 = Принято, 1 = Не запланировано, тип 2 = Короб, 0 = Допринято; прочие коды показываются числом, пока не увидим их в кабинете. Столбца «Упаковано» в API нет, поэтому в представлении его тоже нет: сверять расхождение приёмки можно только по «Добавлено» и «Принято».';
