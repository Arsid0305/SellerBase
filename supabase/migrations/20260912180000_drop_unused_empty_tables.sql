-- Удалить пустые таблицы, заведённые заранее и так и не задействованные.
--
-- Решение владелицы 12.09.2026: «те таблицы и функции, которые мы ещё не
-- завели, но под них заранее зачем-то создали пустые таблицы — удаляем
-- пустоту, будем заводить по мере надобности».
--
-- Перед удалением проверено по каждой: ноль строк, ноль обращений из кода
-- сайта и функций, ноль упоминаний в функциях базы, ноль внешних ключей
-- со стороны остающихся таблиц.

-- ── Глубина контура «расследований» ──────────────────────────────────────
-- Цепочка задумывалась так: проблема → расследование → причина → гипотеза →
-- вывод. В коде сайта используется только сама `problems` (страница
-- «Проблемы» и ссылка с главной). Четыре нижних уровня не читает и не
-- пишет никто. Удаляем их, `problems` остаётся.
--
-- Порядок — от детей к родителям, иначе внешние ключи не дадут.
drop table if exists public.knowledge;
drop table if exists public.hypotheses;
drop table if exists public.causes;
drop table if exists public.investigations;

-- ── Поставки, первая версия ──────────────────────────────────────────────
-- Работает `wb_supplies_v2` (73 поставки) и `wb_supply_items_v2` (1303
-- строки). Старая `wb_supplies_fact` пуста, к ней никто не обращается.
-- Представление над ней удаляем тем же движением — иначе оно останется
-- висеть без опоры.
drop view  if exists public.v_wb_supplies_summary;
