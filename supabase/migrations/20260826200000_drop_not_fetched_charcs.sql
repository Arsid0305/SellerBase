-- Категория not_fetched оказалась ошибочной и прятала настоящие пропуски.
--
-- В миграции 20260826190000 поля, которых нет в sku_catalog.characteristics
-- (ТН ВЭД, сертификаты, НДС, страна производства), были помечены как «не тянем
-- с WB» и исключены из процента заполненности: мол, про них честный ответ
-- «не знаем», а не «пусто». Проверка на живых данных это опровергла.
--
-- «ТНВЭД» (charc_id 15000001) приходит в characteristics у 7 SKU — трёх бандажей
-- и четырёх скакалок. «Страна производства» — у одного SKU. Значит WB отдаёт эти
-- поля в characteristics, когда они заполнены, и отсутствие поля означает ровно
-- «пусто». Слепой зоны нет: мы видим всё, что площадка отдаёт.
--
-- Попутно выяснилось, что под ТН ВЭД у WB два разных поля, в зависимости от
-- предмета: 15000001 «ТНВЭД» (бандажи и скакалки — заполнено) и 15004139
-- «Код ТН ВЭД» (десять предметов — пусто). Тянутся оба, второй просто не заполнен,
-- и это работа по карточкам, а не доработка фетча.
--
-- Цена ошибки в цифрах: заполненность показывалась как 50–93% вместо честных
-- 35–66%. Проверено, что несматченных по charc_id пар нет вовсе — все 94
-- заполненные характеристики находят своё поле в справочнике предмета.

DELETE FROM public.wb_charc_source_map WHERE source = 'not_fetched';

ALTER TABLE public.wb_charc_source_map
  DROP CONSTRAINT IF EXISTS wb_charc_source_map_source_check;
ALTER TABLE public.wb_charc_source_map
  ADD CONSTRAINT wb_charc_source_map_source_check CHECK (source IN ('card_field'));

COMMENT ON TABLE public.wb_charc_source_map IS
  'Характеристики, которые приезжают из cards/list не в массиве characteristics, а отдельными полями карточки (бренд, наименование, описание, баркод, габариты). Всё остальное WB отдаёт в characteristics, и его отсутствие означает незаполненность.';
