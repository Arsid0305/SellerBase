-- Метка прогона отдельной колонкой + запрет дублей на уровне базы.
--
-- Зачем. openJobLog при потерянном ответе повторяет вставку. Перед повтором он
-- ищет свою строку по метке — но если первая вставка ещё не завершилась, поиск
-- честно ничего не находит, повтор проходит, и следом завершается первая. Два
-- прогона на одну метку: один навсегда в «running», уборщик запишет его как
-- ошибку. Проверкой в коде эту гонку не закрыть — нужен запрет в базе.
--
-- Индекс без условия: в Postgres NULL-ы уникальному индексу не мешают, поэтому
-- 12 279 старых строк без метки остаются как есть, а ON CONFLICT (run_key)
-- умеет опереться на такой индекс.

ALTER TABLE public.ingestion_log
  ADD COLUMN IF NOT EXISTS run_key uuid;

COMMENT ON COLUMN public.ingestion_log.run_key IS
  'Метка одного вызова openJobLog. Делает повторную вставку после потерянного ответа безопасной: вторая вставка с той же меткой возвращает уже созданную строку, а не заводит дубль.';

CREATE UNIQUE INDEX IF NOT EXISTS ingestion_log_run_key_uniq
  ON public.ingestion_log (run_key);
