-- Уточнение владелицы 04.09: «бустинг получают только товары, которые участвуют
-- в акции». Формулировка в комментариях могла читаться так, будто добавление
-- одного товара поднимает в поиске весь магазин, — это не так.
--
-- Как на самом деле: participation_pct (доля ассортимента в акции) определяет
-- УРОВЕНЬ бустинга, а получают его только заведённые в акцию номенклатуры.
-- Значит skus_to_next читается как «сколько товаров добавить, чтобы у каждого
-- участника буст вырос до next_boost», а не «чтобы буст получил магазин».

COMMENT ON VIEW public.v_wb_promotions_boost IS
  'Акции: текущий бустинг и ближайший порог. ВАЖНО: бустинг получают только товары, заведённые в акцию, а не весь ассортимент. participation_pct — доля ассортимента в акции; от неё зависит, насколько сильный буст получит каждый участник (ranging). Поэтому pct_to_next и skus_to_next читаются так: сколько товаров надо добавить, чтобы у участвующих буст вырос до next_boost.';

COMMENT ON COLUMN public.wb_promotions.participation_pct IS
  'Доля ассортимента в акции. По ней WB определяет уровень бустинга — но получают его только товары-участники, а не магазин целиком';
