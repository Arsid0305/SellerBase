-- Включаем сбор рекламы ВБ.
-- Решение владелицы 17.09.2026: «сборник рекламы включи».
--
-- Расписание было заведено раньше, но выключено, и пока оно выключено,
-- расходы в базе не появятся никогда: программа просто не ходит в
-- рекламный кабинет. Теперь ходит, а в недельной сводке блок рекламы
-- показывается только когда расход больше нуля - пустых строк не будет.
--
-- Правим через cron.alter_job: прямая запись в cron.job запрещена.

SELECT cron.alter_job(
  (SELECT jobid FROM cron.job WHERE jobname = 'fetch-wb-ads-hourly'),
  active := true
);
