-- Рекламу собираем четыре раза в день, а не каждый час.
-- Просьба владелицы 17.09.2026: «4 раза в день».
--
-- Времена по Москве: 05:15, 11:15, 17:15, 23:15. Утренний прогон
-- забирает вчерашний день целиком, остальные три показывают, как
-- расходуется бюджет в течение дня.

SELECT cron.alter_job(
  (SELECT jobid FROM cron.job WHERE jobname = 'fetch-wb-ads-hourly'),
  schedule := '15 2,8,14,20 * * *'
);
