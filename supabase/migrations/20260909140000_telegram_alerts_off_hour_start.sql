-- Сводка в телеграм сдвинута с 08:00 UTC на 08:10 (с 11:00 на 11:10 МСК).
--
-- 09.09.2026. Причина: detect-anomalies ходит ежечасно в «0 * * * *», сводка
-- стартовала в «0 8 * * *» — ровно раз в сутки они начинались в одну секунду.
-- По логам шлюза за 08:00:02 в эту миллисекунду уходило 24 запроса, и два из
-- них (sku_catalog и wb_commissions_by_subject) получали 504 через 5 секунд,
-- не дождавшись свободного соединения. Отсюда две жёлтых строки в сводке
-- каждый день: «Дефицит: не удалось посчитать» и «Комиссии WB: не удалось
-- проверить».
--
-- Основное лечение — в самой функции: тринадцать проверок выстроены в цепочку
-- вместо Promise.all, теперь она держит не больше трёх запросов разом. Сдвиг
-- расписания — подстраховка: даже трём запросам незачем толкаться с ежечасным
-- поиском аномалий.
--
-- Меняем только расписание, команда задания остаётся прежней.
SELECT cron.alter_job(
  (SELECT jobid FROM cron.job WHERE jobname = 'telegram-alerts-daily'),
  schedule := '10 8 * * *'
);
